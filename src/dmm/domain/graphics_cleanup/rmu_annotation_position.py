def _format_number(value: float) -> str:
    if not math.isfinite(value):
        raise ValueError(f"非有限数值：{value}")
    rounded = round(value)
    if abs(value - rounded) < 1e-9:
        return str(int(rounded))
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return "0" if text in {"-0", "-0.0"} else text


def _translate_number(value: str, delta: float) -> str:
    try:
        return _format_number(float(value) + delta)
    except (TypeError, ValueError):
        return value


def _translate_path_xy(value: str, delta_x: float, delta_y: float) -> str:
    return _PATH_COORD_PATTERN.sub(
        lambda match: (
            f"{_translate_number(match.group(1), delta_x)},"
            f"{_translate_number(match.group(2), delta_y)}"
        ),
        value,
    )


def _translate_element_xy(element: ET.Element, delta_x: float, delta_y: float) -> bool:
    if abs(delta_x) <= 1e-9 and abs(delta_y) <= 1e-9:
        return False
    changed = False
    for node in element.iter():
        for attr in _X_POSITION_ATTRS:
            if attr in node.attrib:
                old = node.get(attr, "")
                new = _translate_number(old, delta_x)
                if new != old:
                    node.set(attr, new)
                    changed = True
        for attr in _Y_POSITION_ATTRS:
            if attr in node.attrib:
                old = node.get(attr, "")
                new = _translate_number(old, delta_y)
                if new != old:
                    node.set(attr, new)
                    changed = True
        if "d" in node.attrib:
            old = node.get("d", "")
            new = _translate_path_xy(old, delta_x, delta_y)
            if new != old:
                node.set("d", new)
                changed = True
    return changed


def _write_tree_atomic(root: ET.Element, output_path: Path) -> None:
    output_path = Path(output_path)
    temp = output_path.with_name(output_path.name + ".tmp_rmu_annotation_position")
    ET.ElementTree(root).write(temp, encoding="utf-8", xml_declaration=True)
    ET.parse(temp)
    os.replace(temp, output_path)


def _is_nop_text(obj: GObject) -> bool:
    if obj.tag.lower() != "text":
        return False
    value = str(obj.attrs.get("ts") or "").strip().upper()
    return re.sub(r"[\s._-]+", "", value) == "NOP"


def _frame_key(frame: RmuFrame) -> tuple[int, str]:
    return frame.frame.xml_index, frame.frame.xml_id


def _element_map(parsed: ParsedG) -> dict[int, ET.Element]:
    # GParser assigns xml_index from enumerate(layer.iter()) while skipping the
    # layer itself. Rebuild the same mapping on the exact parsed XML tree.
    return {
        idx: element
        for idx, element in enumerate(parsed.layer.iter())
        if element is not parsed.layer
    }


def _new_makkah_parser() -> GParser:
    return GParser(
        required_rmu_tags={"CBreakerDis", "ZhaiWaiJieDiDaoZha", "BusDis"},
        label_regex=RMU_LABEL_PATTERN,
        max_distance=RMU_LABEL_SEARCH_MAX_DISTANCE,
        overlap_tolerance=RMU_LABEL_EDGE_TOLERANCE,
        excluded_rmu_name_strings=DEFAULT_RMU_NAME_EXCLUSIONS,
        exclude_numeric_decimal_rmu_names=True,
        exclude_phone_like_rmu_names=True,
        exclude_hyphenated_rmu_names=True,
        prefer_pure_numeric_rmu_names=False,
    )


def _objects_inside_frame(parsed: ParsedG, frame: RmuFrame) -> list[GObject]:
    return [
        obj
        for obj in parsed.objects
        if obj is not frame.frame
        and frame.frame.box.center_contains(obj.box, tolerance=1.0)
    ]


def _assign_nops_to_frames(
    parsed: ParsedG,
    frames: list[RmuFrame],
) -> tuple[list[tuple[GObject, RmuFrame]], list[GObject]]:
    """Assign each NOP Text to the nearest RMU frame once.

    The 330-unit cap mirrors the existing feeder-ownership NOP search radius.
    Global nearest assignment prevents one NOP Text from being consumed by two
    neighbouring cabinets.
    """
    pairs: list[tuple[float, int, int, GObject, RmuFrame]] = []
    nops = [obj for obj in parsed.objects if _is_nop_text(obj)]
    for nop in nops:
        for frame in frames:
            distance = nop.box.edge_distance(frame.frame.box)
            if distance <= NOP_RMU_SEARCH_DISTANCE:
                pairs.append((
                    float(distance),
                    int(nop.xml_index),
                    int(frame.frame.xml_index),
                    nop,
                    frame,
                ))
    pairs.sort(key=lambda item: (item[0], item[1], item[2]))
    used_nops: set[int] = set()
    assignments: list[tuple[GObject, RmuFrame]] = []
    for _distance, _nop_order, _frame_order, nop, frame in pairs:
        if nop.xml_index in used_nops:
            continue
        used_nops.add(nop.xml_index)
        assignments.append((nop, frame))
    unmatched = [nop for nop in nops if nop.xml_index not in used_nops]
    return assignments, unmatched


def _named_yq_switches(
    parser: GParser,
    parsed: ParsedG,
    frame: RmuFrame,
) -> list[tuple[GObject, str]]:
    """Return in-frame CBreakerDis devices whose logical name is Y* or Q*.

    ``p_NameString`` is authoritative when it already contains Y1/Q1-style
    engineering names.  Visible graphical text is used only as the same
    fallback already used by the Makkah RMU validator.  This deliberately
    excludes unrelated disconnectors/grounds so NOP can never align to a
    random symbol merely because it is geometrically close.
    """
    breakers = [
        obj
        for obj in _objects_inside_frame(parsed, frame)
        if obj.tag == "CBreakerDis"
    ]
    if not breakers:
        return []

    try:
        graphical = parser.resolve_breaker_graphical_names(parsed, frame, breakers)
    except Exception:
        graphical = {}

    result: list[tuple[GObject, str]] = []
    for device in breakers:
        logical_name = str(device.xml_p_name_string or "").strip().upper()
        if not re.fullmatch(r"[YQ]\d+", logical_name):
            info = graphical.get(device.xml_id, {}) if graphical else {}
            visible = (
                str(info.get("name") or "").strip().upper()
                if info.get("status") == "PASS"
                else ""
            )
            logical_name = visible
        if re.fullmatch(r"[YQ]\d+", logical_name):
            result.append((device, logical_name))

    def _name_key(item):
        device, name = item
        prefix = 0 if name.startswith("Y") else 1
        try:
            number = int(name[1:])
        except ValueError:
            number = 10**9
        return prefix, number, device.xml_index

    return sorted(result, key=_name_key)


def _corresponding_nop_device(
    parser: GParser,
    parsed: ParsedG,
    frame: RmuFrame,
    nop: GObject,
    preferred_side: str = "auto",
) -> tuple[GObject, str] | None:
    """Resolve the Y*/Q* switch whose row the NOP belongs to.

    The NOP's display side also carries useful field-layout evidence.  A NOP
    shown on the right should first consider Y*/Q* switches on the right half
    of the cabinet (and likewise for the left), then choose the closest switch
    row by center-Y distance.  This prevents a right-side NOP from jumping to a
    left-side Y/Q device merely because the two rows happen to be close.
    """
    fb = frame.frame.box
    side = preferred_side
    if side == "auto":
        side = "left" if nop.box.cx < fb.cx else "right"

    candidates = []
    for device, logical_name in _named_yq_switches(parser, parsed, frame):
        device_side = "left" if device.box.cx < fb.cx else "right"
        side_penalty = 0 if device_side == side else 1
        candidates.append((
            side_penalty,
            abs(float(nop.box.cy) - float(device.box.cy)),
            float(nop.box.edge_distance(device.box)),
            abs(float(nop.box.cx) - float(device.box.cx)),
            int(device.xml_index),
            device,
            logical_name,
        ))
    if not candidates:
        return None
    candidates.sort(key=lambda item: item[:5])
    return candidates[0][5], candidates[0][6]


def _target_for_rmu_name(frame: RmuFrame, name: GObject, side: str, margin: float) -> tuple[float, float]:
    fb = frame.frame.box
    nb = name.box
    if side == "top":
        return fb.cx - nb.w / 2.0, fb.top - margin - nb.h
    if side == "bottom":
        return fb.cx - nb.w / 2.0, fb.bottom + margin
    if side == "left":
        return fb.left - margin - nb.w, fb.cy - nb.h / 2.0
    if side == "right":
        return fb.right + margin, fb.cy - nb.h / 2.0
    raise ValueError(f"不支持的环网柜名称位置：{side!r}")


def _target_for_nop(
    frame: RmuFrame,
    device: GObject,
    nop: GObject,
    side: str,
    margin: float,
) -> tuple[float, float, str]:
    """Place NOP left/right of the RMU and center-align it with its Y*/Q* switch.

    Horizontal alignment means both centers share the same Y coordinate.  The
    X coordinate only decides which cabinet side the NOP is displayed on.
    ``auto`` preserves the NOP's existing left/right side whenever possible.
    """
    fb = frame.frame.box
    db = device.box
    nb = nop.box
    resolved_side = side
    if side == "auto":
        resolved_side = "left" if nb.cx < fb.cx else "right"
    if resolved_side == "left":
        target_x = fb.left - margin - nb.w
    elif resolved_side == "right":
        target_x = fb.right + margin
    else:
        raise ValueError(f"不支持的 NOP 位置：{side!r}")
    target_y = db.cy - nb.h / 2.0
    return target_x, target_y, resolved_side


def reposition_rmu_annotations(
    parsed: ParsedG,
    *,
    nop_position: str = "auto",
    rmu_name_position: str = "right",
    nop_margin: float = 5.0,
    rmu_name_margin: float = 5.0,
) -> dict[str, int]:
    if nop_position not in NOP_HORIZONTAL_POSITIONS:
        raise ValueError(f"不支持的 NOP 位置：{nop_position!r}")
    if rmu_name_position not in RMU_NAME_POSITIONS:
        raise ValueError(f"不支持的环网柜名称位置：{rmu_name_position!r}")
    if float(nop_margin) < 0 or float(rmu_name_margin) < 0:
        raise ValueError("距边像素不能小于 0。")

    parser = _new_makkah_parser()
    # The parser methods use only ParsedG data, so keep the already parsed tree
    # instead of re-reading the file and risking a different element mapping.
    frames = parser.find_rmu_frames(parsed)
    elements = _element_map(parsed)

    # Makkah RMU-name ownership is RIGHT -> BOTTOM -> GLOBAL fallback.
    assigned_names = parser.assign_rmu_label_candidates_globally(
        parsed,
        frames,
        ("right", "bottom", "global"),
    )

    name_found = 0
    name_moved = 0
    name_missing = 0
    rmu_name_poke_found = 0
    rmu_name_poke_moved = 0
    moved_poke_objects: set[int] = set()
    for frame in frames:
        candidates = assigned_names.get(_frame_key(frame), [])
        if not candidates:
            name_missing += 1
            continue
        name = candidates[0].obj
        element = elements.get(name.xml_index)
        if element is None:
            name_missing += 1
            continue
        name_found += 1
        target_x, target_y = _target_for_rmu_name(
            frame,
            name,
            rmu_name_position,
            float(rmu_name_margin),
        )
        delta_x = target_x - name.box.x
        delta_y = target_y - name.box.y
        related_pokes = _related_name_pokes(parsed, name)
        rmu_name_poke_found += len(related_pokes)
        if _translate_element_xy(element, delta_x, delta_y):
            name_moved += 1
            # A Poke is an invisible click region linked to the name Text.  It
            # must receive the exact same translation, otherwise the visible
            # label and its clickable jump target become separated.
            for poke in related_pokes:
                poke_key = id(poke)
                if poke_key in moved_poke_objects:
                    continue
                if _translate_element_xy(poke, delta_x, delta_y):
                    rmu_name_poke_moved += 1
                moved_poke_objects.add(poke_key)

    nop_assignments, unmatched_nops = _assign_nops_to_frames(parsed, frames)
    nop_found = len(nop_assignments) + len(unmatched_nops)
    nop_moved = 0
    nop_unmatched_device = 0
    for nop, frame in nop_assignments:
        resolved = _corresponding_nop_device(
            parser, parsed, frame, nop, preferred_side=nop_position
        )
        if resolved is None:
            nop_unmatched_device += 1
            continue
        device, device_name = resolved
        element = elements.get(nop.xml_index)
        if element is None:
            nop_unmatched_device += 1
            continue
        target_x, target_y, resolved_side = _target_for_nop(
            frame,
            device,
            nop,
            nop_position,
            float(nop_margin),
        )
        if _translate_element_xy(element, target_x - nop.box.x, target_y - nop.box.y):
            nop_moved += 1

    return {
        "rmu_count": len(frames),
        "rmu_name_found": name_found,
        "rmu_name_moved": name_moved,
        "rmu_name_missing": name_missing,
        "rmu_name_poke_found": rmu_name_poke_found,
        "rmu_name_poke_moved": rmu_name_poke_moved,
        "nop_found": nop_found,
        "nop_moved": nop_moved,
        "nop_unmatched_rmu": len(unmatched_nops),
        "nop_unmatched_device": nop_unmatched_device,
    }


def _write_csv(records: list[RmuAnnotationPositionFileRecord], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(RmuAnnotationPositionFileRecord.__dataclass_fields__)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for record in records:
            writer.writerow(asdict(record))
    return path


