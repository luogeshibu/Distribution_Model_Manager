# Makkah annotation layout rules.
#
# * RMU cabinet names are anchored at the midpoint of one of the four frame
#   edges (top/right/bottom/left).
# * NOP is NOT centered to the RMU frame.  It belongs to an in-cabinet Y*/Q*
#   switch (Y1/Y2/Y3/Q1/Q2/Q3...) and must be horizontally center-aligned with
#   that switch, i.e. NOP.center_y == switch.center_y.  NOP therefore lives on
#   the left or right side of the cabinet only.
RMU_NAME_POSITIONS: dict[str, str] = {
    "top": "上边中点",
    "right": "右边中点",
    "bottom": "下边中点",
    "left": "左边中点",
}

NOP_HORIZONTAL_POSITIONS: dict[str, str] = {
    "auto": "自动保持原左右侧",
    "left": "左侧（与开关水平中心对齐）",
    "right": "右侧（与开关水平中心对齐）",
}

# Backward-compatible alias for earlier internal callers/tests.
EDGE_CENTER_POSITIONS = RMU_NAME_POSITIONS

NOP_RMU_SEARCH_DISTANCE = 330.0

_PATH_COORD_PATTERN = re.compile(r"(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)")
_X_POSITION_ATTRS = ("x", "x1", "x2", "cx", "mergex")
_Y_POSITION_ATTRS = ("y", "y1", "y2", "cy", "mergey")

# Poke objects generated by G File Studio / DMM carry one of these Text-ID
# metadata fields.  Older field drawings may contain a plain <poke> without
# metadata, so a strict geometry fallback is also used below.
_POKE_TEXT_ID_ATTRS = (
    "dmm_source_text_id",
    "dmm_rmu_text_id",
    "gfs_rmu_text_id",
)


def _local_name(tag) -> str:
    return str(tag or "").rsplit("}", 1)[-1]


def _element_box(element: ET.Element):
    try:
        x = float(element.get("x", "0"))
        y = float(element.get("y", "0"))
        w = float(element.get("w", element.get("width", "0")))
        h = float(element.get("h", element.get("height", "0")))
    except (TypeError, ValueError):
        return None
    if w <= 0 or h <= 0:
        return None
    return x, y, w, h


def _box_overlap_ratio(a, b) -> float:
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    ix = max(0.0, min(ax + aw, bx + bw) - max(ax, bx))
    iy = max(0.0, min(ay + ah, by + bh) - max(ay, by))
    intersection = ix * iy
    base = min(max(aw * ah, 1e-9), max(bw * bh, 1e-9))
    return intersection / base


def _related_name_pokes(parsed: ParsedG, name: GObject) -> list[ET.Element]:
    """Return Poke click-regions owned by one RMU name Text.

    Prefer explicit Text-ID metadata written by G File Studio/DMM.  For older
    drawings without metadata, accept only an ahref-bearing Poke whose click box
    substantially overlaps the RMU-name Text box.  This avoids moving unrelated
    Pokes merely because they are nearby.
    """
    text_id = str(name.xml_id or "").strip()
    name_box = (float(name.box.x), float(name.box.y), float(name.box.w), float(name.box.h))
    explicit: list[ET.Element] = []
    geometric: list[ET.Element] = []
    for element in parsed.layer.iter():
        if _local_name(element.tag).lower() != "poke":
            continue
        if text_id and any(str(element.get(attr) or "").strip() == text_id for attr in _POKE_TEXT_ID_ATTRS):
            explicit.append(element)
            continue
        if not str(element.get("ahref") or "").strip():
            continue
        poke_box = _element_box(element)
        if poke_box is None:
            continue
        if _box_overlap_ratio(name_box, poke_box) >= 0.80:
            geometric.append(element)
    # Explicit ownership is authoritative.  Geometry fallback is used only when
    # no metadata-linked Poke exists for this Text.
    return explicit if explicit else geometric


