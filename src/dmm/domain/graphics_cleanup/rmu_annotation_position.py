def process_rmu_annotation_reposition(
    files: Iterable[Path],
    output_dir: Path,
    report_dir: Path,
    *,
    nop_position: str = "auto",
    rmu_name_position: str = "right",
    nop_margin: int = 5,
    rmu_name_margin: int = 5,
    log=None,
    progress=None,
) -> RmuAnnotationPositionResult:
    if nop_position not in NOP_HORIZONTAL_POSITIONS:
        raise ValueError(f"不支持的 NOP 位置：{nop_position!r}")
    if rmu_name_position not in RMU_NAME_POSITIONS:
        raise ValueError(f"不支持的环网柜名称位置：{rmu_name_position!r}")
    if int(nop_margin) < 0 or int(rmu_name_margin) < 0:
        raise ValueError("距边像素不能小于 0。")

    log = log or (lambda _message: None)
    files = [Path(path) for path in files]
    if not files:
        raise ValueError("没有可处理的 G 文件。")

    output_dir = Path(output_dir)
    report_dir = Path(report_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    report_dir.mkdir(parents=True, exist_ok=True)

    output_files: list[Path] = []
    records: list[RmuAnnotationPositionFileRecord] = []
    totals = {
        "rmu_name_found": 0,
        "rmu_name_moved": 0,
        "rmu_name_missing": 0,
        "rmu_name_poke_found": 0,
        "rmu_name_poke_moved": 0,
        "nop_found": 0,
        "nop_moved": 0,
        "nop_unmatched_rmu": 0,
        "nop_unmatched_device": 0,
    }

    parser = _new_makkah_parser()
    for index, source in enumerate(files, start=1):
        if progress:
            progress(
                int((index - 1) / max(1, len(files)) * 95),
                f"正在调整 NOP / 环网柜名称：{source.name}",
            )
        target = output_dir / source.name
        shutil.copy2(source, target)
        log(f"[安全副本] {source} -> {target}")

        parsed = parser.parse(target)
        counts = reposition_rmu_annotations(
            parsed,
            nop_position=nop_position,
            rmu_name_position=rmu_name_position,
            nop_margin=float(nop_margin),
            rmu_name_margin=float(rmu_name_margin),
        )
        _write_tree_atomic(parsed.root, target)

        for key in totals:
            totals[key] += int(counts[key])
        moved_total = int(counts["rmu_name_moved"]) + int(counts["nop_moved"])
        found_total = int(counts["rmu_name_found"]) + int(counts["nop_found"])
        status = "MOVED" if moved_total else ("ALREADY_AT_TARGET" if found_total else "NO_MATCH")
        record = RmuAnnotationPositionFileRecord(
            file_name=target.name,
            rmu_count=int(counts["rmu_count"]),
            rmu_name_found=int(counts["rmu_name_found"]),
            rmu_name_moved=int(counts["rmu_name_moved"]),
            rmu_name_missing=int(counts["rmu_name_missing"]),
            rmu_name_poke_found=int(counts["rmu_name_poke_found"]),
            rmu_name_poke_moved=int(counts["rmu_name_poke_moved"]),
            nop_found=int(counts["nop_found"]),
            nop_moved=int(counts["nop_moved"]),
            nop_unmatched_rmu=int(counts["nop_unmatched_rmu"]),
            nop_unmatched_device=int(counts["nop_unmatched_device"]),
            nop_position=nop_position,
            rmu_name_position=rmu_name_position,
            nop_margin=int(nop_margin),
            rmu_name_margin=int(rmu_name_margin),
            status=status,
        )
        records.append(record)
        output_files.append(target)
        log(
            f"[NOP/名称位置] {target.name}: 有效RMU={record.rmu_count}, "
            f"名称找到={record.rmu_name_found}, 名称移动={record.rmu_name_moved}, "
            f"名称Poke找到={record.rmu_name_poke_found}, 名称Poke移动={record.rmu_name_poke_moved}, "
            f"NOP找到={record.nop_found}, NOP移动={record.nop_moved}, "
            f"NOP无RMU={record.nop_unmatched_rmu}, NOP无柜内设备={record.nop_unmatched_device}, "
            f"NOP位置={NOP_HORIZONTAL_POSITIONS[nop_position]}, "
            f"名称位置={RMU_NAME_POSITIONS[rmu_name_position]}"
        )

    csv_path = _write_csv(records, report_dir / "rmu_annotation_position_report.csv")
    html_path = _write_html(records, report_dir / "rmu_annotation_position_report.html")
    if progress:
        progress(100, "NOP / 环网柜名称位置调整完成")
    return RmuAnnotationPositionResult(
        output_files=output_files,
        records=records,
        csv_path=csv_path,
        html_path=html_path,
        **totals,
    )
